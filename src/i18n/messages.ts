const arPlural = (n: number, f: { zero: string; one: string; two: string; few: string; many: string }) => {
  const r = new Intl.PluralRules('ar').select(n);
  return r === 'zero' ? f.zero : r === 'one' ? f.one : r === 'two' ? f.two : r === 'few' ? f.few : f.many;
};

